// Builds the static preview deployment into build/:
//   sw.js        the transpiled gateway + sql.js in a service worker
//   index.html   installs the worker, then goes to app/
//   app/         the Fiori Elements demo app, service URI relative to the mount
// Run after `npm run transpile`. No server is involved: GitHub Pages (or any
// static host) serves these files, the worker answers the OData requests.
import {copyFile, mkdir, readFile, readdir, writeFile, stat} from "node:fs/promises";
import {createHash} from "node:crypto";
import {createRequire} from "node:module";
import {join, resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {seedStatements} from "../test/seed.mjs";
import {services as icfServices, channels as apcChannels} from "../tools/osd-icf.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const generated = resolve(root, "web/generated");
const build = resolve(root, "build");

// the seed rows, and a build id that tells a stored browser database from a
// deployment it no longer fits
await mkdir(generated, {recursive: true});
const seed = seedStatements(resolve(root, "data"), resolve(root, "src/ddic"));
const init = await readFile(resolve(root, "output/init.mjs"), "utf8");
const buildId = createHash("sha256").update(init).update(seed.join("\n")).digest("hex").slice(0, 16);
await writeFile(resolve(generated, "seed.mjs"),
  "// Generated by scripts/build-preview.mjs. Do not edit.\n"
  + `export const buildId = ${JSON.stringify(buildId)};\n`
  + `export const seed = ${JSON.stringify(seed, undefined, 2)};\n`, "utf8");
console.log(`Seed: ${seed.length} statements, build ${buildId}`);

// The services this deployment answers, written out so the worker and the
// backend agree without either hard-coding a path.
//
// The OData front is one of them rather than a special case: it is an
// if_http_extension on a prefix exactly like the rest, and the only reason it
// used to be written into two files by hand is that it was the only one. A
// repository imported under local/ brings its own *.sicf.xml and appears here
// with no change to this script.
const RESERVED = [];
const table = [
  {path: "/sap/opu/odata/sap", handler: "ZCL_STG_HTTP_HANDLER", name: "OData"},
  ...icfServices(root, {roots: ["src", "local", "test", "gen"]})
    .filter((s) => s.handler !== undefined)
    .filter((s) => RESERVED.includes(s.path) === false)
    .map((s) => ({path: s.path, handler: s.handler, name: s.name})),
];
// the push channels, from the *.sapc.xml objects, on the same principle: a
// page opens ws://host<path> and the worker drives that handler
const channels = apcChannels(root, {roots: ["src", "local", "test", "gen"]})
  .map((c) => ({path: c.path, handler: c.handler, name: c.name}));
await writeFile(resolve(generated, "services.mjs"),
  "// Generated by scripts/build-preview.mjs. Do not edit.\n"
  + `export const services = ${JSON.stringify(table, undefined, 2)};\n`
  + `export const channels = ${JSON.stringify(channels, undefined, 2)};\n`, "utf8");
console.log(`Services: ${table.map((s) => s.path).join(", ")}`);
console.log(`Channels: ${channels.length === 0 ? "(none)" : channels.map((c) => c.path).join(", ")}`);

const require = createRequire(import.meta.url);
const webpack = require("webpack");
const configuration = require(resolve(root, "webpack.config.cjs"));
const statistics = await new Promise((fulfil, reject) => {
  webpack(configuration, (error, result) => {
    if (error) {
      reject(error);
    } else if (result.hasErrors()) {
      reject(new Error(result.toString({colors: false, errorDetails: true})));
    } else {
      fulfil(result);
    }
  });
});
console.log(statistics.toString({colors: false, preset: "minimal"}));

await mkdir(build, {recursive: true});
await copyFile(resolve(root, "web/index.html"), resolve(build, "index.html"));

// the app: copied as is, except index.html makes sure the worker controls the
// page before UI5 boots (a deep link into app/ must work without going
// through the root page first)
async function copyTree(from, to) {
  await mkdir(to, {recursive: true});
  for (const entry of await readdir(from)) {
    const source = join(from, entry);
    if ((await stat(source)).isDirectory()) {
      await copyTree(source, join(to, entry));
    } else {
      await copyFile(source, join(to, entry));
    }
  }
}
await copyTree(resolve(root, "webapp"), resolve(build, "app"));
// the two entry pages: the Travels app alone, and the launchpad sandbox with
// both apps; each boots UI5 only once the worker answers
for (const page of ["index.html", "flp.html"]) {
  await deferBootstrap(page);
}

async function deferBootstrap(page) {
const index = await readFile(resolve(root, "webapp", page), "utf8");
const bootstrap = /<script id="sap-ui-bootstrap"[\s\S]*?<\/script>/.exec(index);
if (bootstrap === null) {
  throw new Error(`webapp/${page}: sap-ui-bootstrap script not found`);
}
// the bootstrap tag's attributes, set on a script element the loader creates
// once the worker controls the page (the tag itself must not appear inside a
// script: "</script>" would end it)
const attributes = {};
for (const m of bootstrap[0].replace(/^<script /, "").matchAll(/([\w-]+)="([^"]*)"|([\w-]+)='([^']*)'/g)) {
  attributes[m[1] ?? m[3]] = m[2] ?? m[4];
}
const loader = `<script>
    // preview deployment: the OData service is answered by a service worker,
    // so it has to control this page before UI5 asks for $metadata. When it
    // cannot, say so instead of booting into a blank list report.
    (async () => {
      const explain = (title, detail) => {
        document.body.innerHTML = "";
        const main = document.createElement("main");
        main.style.cssText = "max-width:40rem;margin:3rem auto;padding:0 1rem;font:16px/1.5 system-ui,sans-serif";
        const h = document.createElement("h1");
        h.style.fontSize = "1.3rem";
        h.textContent = title;
        const p = document.createElement("pre");
        p.style.whiteSpace = "pre-wrap";
        p.textContent = detail;
        const a = document.createElement("p");
        a.innerHTML = 'The gateway runs in a service worker. <a href="../">Install it again</a>, try another browser, or check that service workers and site data are allowed for this site.';
        main.append(h, p, a);
        document.body.append(main);
      };
      if (!("serviceWorker" in navigator)) {
        explain("This browser cannot run the preview", "navigator.serviceWorker is not available (private window, or service workers turned off).");
        return;
      }
      if (!navigator.serviceWorker.controller) {
        try {
          await navigator.serviceWorker.register("../sw.js", {scope: "../"});
          await navigator.serviceWorker.ready;
          // clients.claim() in the worker makes this page controlled a moment
          // after ready; the event for it may already have fired, so poll
          for (let waited = 0; !navigator.serviceWorker.controller && waited < 5000; waited += 100) {
            await new Promise((tick) => setTimeout(tick, 100));
          }
          if (!navigator.serviceWorker.controller) {
            // a navigation after the registration is controlled for sure; once
            const key = "stg-preview-reload";
            if (!sessionStorage.getItem(key)) {
              sessionStorage.setItem(key, "1");
              location.reload();
              return;
            }
            sessionStorage.removeItem(key);
            throw new Error("the service worker was installed but does not control this page");
          }
        } catch (error) {
          explain("The preview could not start", String(error && error.stack || error));
          return;
        }
      }
      // one round trip before UI5: the worker must be the one answering
      try {
        const probe = await fetch("../sap/opu/odata/sap/ZSTG_DEMO_SRV/", {headers: {accept: "application/json"}});
        if (!probe.ok) {
          explain("The gateway did not answer", "GET ../sap/opu/odata/sap/ZSTG_DEMO_SRV/ returned " + probe.status + "\\n\\n" + (await probe.text()).slice(0, 2000));
          return;
        }
      } catch (error) {
        explain("The gateway did not answer", String(error));
        return;
      }
      const boot = document.createElement("script");
      const attributes = ${JSON.stringify(attributes)};
      for (const name of Object.keys(attributes)) {
        boot.setAttribute(name, attributes[name]);
      }
      document.head.appendChild(boot);
    })();
  </script>`;
await writeFile(resolve(build, "app", page), index.replace(bootstrap[0], loader), "utf8");
}
// the page-side websocket shim, beside the worker rather than inside it:
// it runs in the document, not in the worker, and the worker injects a tag
// pointing at it
await copyFile(resolve(root, "web/preview-socket.mjs"), resolve(build, "preview-socket.mjs"));

console.log(`Preview build is in ${build}`);
