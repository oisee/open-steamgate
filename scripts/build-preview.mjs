// Builds the static preview deployment into build/:
//   sw.js        the transpiled gateway + sql.js in a service worker
//   index.html   installs the worker, then goes to app/
//   app/         the Fiori Elements demo app, service URI relative to the mount
// Run after `npm run transpile`. No server is involved: GitHub Pages (or any
// static host) serves these files, the worker answers the OData requests.
import {copyFile, mkdir, readFile, readdir, writeFile, stat} from "node:fs/promises";
import {createHash} from "node:crypto";
import {createRequire} from "node:module";
import {join, resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {seedStatements} from "../test/seed.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const generated = resolve(root, "web/generated");
const build = resolve(root, "build");

// the seed rows, and a build id that tells a stored browser database from a
// deployment it no longer fits
await mkdir(generated, {recursive: true});
const seed = seedStatements(resolve(root, "data"), resolve(root, "src/ddic"));
const init = await readFile(resolve(root, "output/init.mjs"), "utf8");
const buildId = createHash("sha256").update(init).update(seed.join("\n")).digest("hex").slice(0, 16);
await writeFile(resolve(generated, "seed.mjs"),
  "// Generated by scripts/build-preview.mjs. Do not edit.\n"
  + `export const buildId = ${JSON.stringify(buildId)};\n`
  + `export const seed = ${JSON.stringify(seed, undefined, 2)};\n`, "utf8");
console.log(`Seed: ${seed.length} statements, build ${buildId}`);

const require = createRequire(import.meta.url);
const webpack = require("webpack");
const configuration = require(resolve(root, "webpack.config.cjs"));
const statistics = await new Promise((fulfil, reject) => {
  webpack(configuration, (error, result) => {
    if (error) {
      reject(error);
    } else if (result.hasErrors()) {
      reject(new Error(result.toString({colors: false, errorDetails: true})));
    } else {
      fulfil(result);
    }
  });
});
console.log(statistics.toString({colors: false, preset: "minimal"}));

await mkdir(build, {recursive: true});
await copyFile(resolve(root, "web/index.html"), resolve(build, "index.html"));

// the app: copied as is, except index.html makes sure the worker controls the
// page before UI5 boots (a deep link into app/ must work without going
// through the root page first)
async function copyTree(from, to) {
  await mkdir(to, {recursive: true});
  for (const entry of await readdir(from)) {
    const source = join(from, entry);
    if ((await stat(source)).isDirectory()) {
      await copyTree(source, join(to, entry));
    } else {
      await copyFile(source, join(to, entry));
    }
  }
}
await copyTree(resolve(root, "webapp"), resolve(build, "app"));
const index = await readFile(resolve(root, "webapp/index.html"), "utf8");
const bootstrap = /<script id="sap-ui-bootstrap"[\s\S]*?<\/script>/.exec(index);
if (bootstrap === null) {
  throw new Error("webapp/index.html: sap-ui-bootstrap script not found");
}
// the bootstrap tag's attributes, set on a script element the loader creates
// once the worker controls the page (the tag itself must not appear inside a
// script: "</script>" would end it)
const attributes = {};
for (const m of bootstrap[0].replace(/^<script /, "").matchAll(/([\w-]+)="([^"]*)"|([\w-]+)='([^']*)'/g)) {
  attributes[m[1] ?? m[3]] = m[2] ?? m[4];
}
const loader = `<script>
    // preview deployment: the OData service is answered by a service worker,
    // so it has to control this page before UI5 asks for $metadata
    (async () => {
      if ("serviceWorker" in navigator && !navigator.serviceWorker.controller) {
        try {
          await navigator.serviceWorker.register("../sw.js", {scope: "../"});
          await navigator.serviceWorker.ready;
          if (!navigator.serviceWorker.controller) {
            await new Promise((done) => navigator.serviceWorker.addEventListener("controllerchange", done, {once: true}));
          }
        } catch (error) {
          console.error("preview: service worker not installed", error);
        }
      }
      const boot = document.createElement("script");
      const attributes = ${JSON.stringify(attributes)};
      for (const name of Object.keys(attributes)) {
        boot.setAttribute(name, attributes[name]);
      }
      document.head.appendChild(boot);
    })();
  </script>`;
await writeFile(resolve(build, "app/index.html"), index.replace(bootstrap[0], loader), "utf8");
console.log(`Preview build is in ${build}`);
