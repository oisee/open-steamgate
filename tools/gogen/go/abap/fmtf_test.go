package abap

import "testing"

// the fifteen values measured on A4H, 2026-09-23
func TestFmtF(t *testing.T) {
	cases := []struct {
		v    float64
		want string
	}{
		{1.5, "1.5"}, {0, "0"}, {-0.25, "-0.25"}, {0.1, "0.10000000000000001"}, {1.0 / 3, "0.33333333333333331"},
		{123456789.125, "123456789.125"}, {1e20, "100000000000000000000"}, {1e-7, "0.000000099999999999999995"},
		{2, "2"}, {3.6000000000000001, "3.6000000000000001"}, {0.024671052631575208 * 1.5, "0.037006578947362812"},
		{1e15, "1000000000000000"}, {1e16, "10000000000000000"}, {0.001, "0.001"}, {0.0001, "0.0001"},
	}
	for _, c := range cases {
		if got := FmtF(c.v); got != c.want {
			t.Errorf("FmtF(%v) = %q, A4H %q", c.v, got, c.want)
		}
	}
}
