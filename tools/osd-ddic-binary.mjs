// Generate the piece of DDIC type information the transpiler's PostgreSQL
// schema cannot carry: which transparent-table columns are byte strings.
// A real SAP-on-HANA system maps RAW to VARBINARY and RAWSTRING/LRAW to BLOB;
// the generated module lets test/setup.mjs make the same choice before the
// runtime has registered abap.DDIC.
import {existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync} from "node:fs";
import {dirname, join, resolve} from "node:path";
import {contentFoldersOf} from "./osd-packs.mjs";
import {libraryFiles} from "./osd-inputs.mjs";
import {runsAs} from "./osd-main.mjs";

const tag = (xml, name) => new RegExp(`<${name}>([^<]*)</${name}>`, "i").exec(xml)?.[1]?.trim();

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) walk(path, out);
    else if (/\.(?:tabl|dtel)\.xml$/i.test(entry)) out.push(path);
  }
  return out;
}

export function binaryDdIC(root = process.cwd()) {
  const files = contentFoldersOf(root).flatMap((folder) => walk(resolve(root, folder)));
  for (const lib of libraryFiles(root)) {
    for (const file of lib.files) if (/\.(?:tabl|dtel)\.xml$/i.test(file)) files.push(file);
  }

  const elements = new Map();
  for (const file of files.filter((f) => /\.dtel\.xml$/i.test(f))) {
    const xml = readFileSync(file, "utf8");
    const name = tag(xml, "ROLLNAME");
    const datatype = tag(xml, "DATATYPE")?.toUpperCase();
    const length = Number(tag(xml, "LENG"));
    if (name && datatype) elements.set(name.toUpperCase(), {datatype, length});
  }

  const result = {};
  for (const file of files.filter((f) => /\.tabl\.xml$/i.test(f))) {
    const xml = readFileSync(file, "utf8");
    const table = tag(xml, "TABNAME")?.toUpperCase();
    if (!table) continue;
    for (const match of xml.matchAll(/<DD03P>([\s\S]*?)<\/DD03P>/gi)) {
      const field = tag(match[1], "FIELDNAME")?.toUpperCase();
      const inherited = elements.get(tag(match[1], "ROLLNAME")?.toUpperCase());
      const datatype = (tag(match[1], "DATATYPE") ?? inherited?.datatype)?.toUpperCase();
      const length = Number(tag(match[1], "LENG") ?? inherited?.length);
      if (!field || !datatype) continue;
      if (datatype === "RAW" && Number.isFinite(length) && length > 0) {
        (result[table] ??= {})[field] = `VARBINARY(${length})`;
      } else if (["RAWSTRING", "RSTR", "LRAW"].includes(datatype)) {
        (result[table] ??= {})[field] = "BLOB";
      }
    }
  }
  return result;
}

export function writeBinaryDdIC(root = process.cwd(), target = join(root, "gen", "osd-ddic-binary.mjs")) {
  mkdirSync(dirname(target), {recursive: true});
  const value = binaryDdIC(root);
  writeFileSync(target, `// generated by tools/osd-ddic-binary.mjs - do not edit\nexport const ddicBinary = ${JSON.stringify(value, null, 2)};\n`);
  return value;
}

if (runsAs("osd-ddic-binary.mjs")) {
  const value = writeBinaryDdIC();
  console.log(`osd-ddic-binary: ${Object.values(value).reduce((n, fields) => n + Object.keys(fields).length, 0)} byte-string columns`);
}
