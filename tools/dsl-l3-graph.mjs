// DSL L3: the set drawn as a diagram (docs/dsl-l3.md, "The graph").
// The graph is read off the compiled model (compileSet), never off the YAML:
// every node and edge carries the set line the model recorded for it, as the
// trace sidecars do. The same model gives byte-identical output, so the
// order of everything is the model's order: stages, rules and ports as the
// manifest lists them, never a sort and never a Map of unknown order.
import {readFileSync} from "node:fs";

export const GRAPH_FORMATS = ["mermaid", "json"];
export const DOC_BEGIN = (set) => `<!-- dsl-l3 graph ${set} begin: generated by node tools/dsl-l3.mjs graph, do not edit -->`;
export const DOC_END = (set) => `<!-- dsl-l3 graph ${set} end -->`;

const per = (n) => `${(Number(n) / 100).toString()}%`;

// The model as {set, nodes, edges, groups}. A node: {id, kind, label, line, group};
// an edge: {from, to, kind, label, line}; a group (a stage's subgraph): {id, label, line, nodes}.
export function graphOf(model) {
  const nodes = [];
  const edges = [];
  const groups = [];
  const seen = new Set();
  const add = (id, kind, label, line, group) => {
    if (seen.has(id)) throw new Error(`graph: node ${id} is made twice`);
    seen.add(id);
    nodes.push({id, kind, label, line: Number(line), ...(group ? {group} : {})});
    return id;
  };
  const link = (from, to, kind, label, line) => edges.push({from, to, kind, ...(label ? {label} : {}), line: Number(line)});
  const group = (id, label, line) => { const g = {id, label, line: Number(line), nodes: []}; groups.push(g); return g; };
  const put = (g, id, kind, label, line) => { add(id, kind, label, line, g.id); g.nodes.push(id); return id; };

  const root = add(model["@id"], "set", `${model.set}: ${model.title}`, model.set_line);

  // ports: the bound variant first, the other variants after it
  const ports = new Map();
  for (const p of model.ports) {
    const others = p.variants.filter((v) => v.name !== p.binding.variant).map((v) => v.name);
    const label = `${p.name} (${p.kind}${p.table && p.kind !== "autoclose" && p.kind !== "work" ? ` ${p.table.toUpperCase()}` : ""})\nbound: ${p.binding.variant}${others.length ? `\nother: ${others.join(", ")}` : ""}`;
    ports.set(p.name, add(p["@id"], `port-${p.kind}`, label, p.set_line));
  }

  const ruleNode = (g, r) => put(g, r["@id"], r.filter ? "rule-filter" : "rule", `${r.name}\n${r.check_class}`, r.set_line);
  const wl = new Map();
  const stageGroup = (id, label, line, pile, members, extra = {}) => {
    const g = group(id, label, line);
    const head = put(g, `${id}/head`, "stage", label, line);
    let from = head;
    if (pile) {
      const src = pile.over_worklist ? `worklist ${pile.over_worklist.name}` : `${pile.source.name} (${pile.source.table.toUpperCase()})`;
      const pn = put(g, pile["@id"], "pile", `piles of ${pile.size}\nsource: ${src}`, pile.set_line);
      link(head, pn, "flow", "", pile.set_line);
      if (pile.over_worklist) wl.set(pn, pile.over_worklist);
      else if (ports.has(pile.source.name)) link(ports.get(pile.source.name), pn, "read", "reads", pile.set_line);
      from = pn;
    }
    const rules = members.map((r) => ruleNode(g, r));
    for (const rn of rules) link(from, rn, "flow", "", nodes.find((n) => n.id === rn).line);
    return {g, head, pile: pile ? from : undefined, rules};
  };

  const heads = [];
  const sinks = model.ports.filter((p) => p.is_sink);
  if (model.stages) {
    const filled = new Map();
    for (const s of model.stages) {
      const label = `stage ${s.no}: ${s.name}${s.filter ? " (filter)" : ""}`;
      const built = stageGroup(s["@id"], label, s.set_line, s.piles, s.members);
      heads.push(built);
      if (s.filter) {
        const w = put(built.g, s.worklist["@id"], "worklist", `worklist ${s.worklist.name}`, s.worklist.set_line);
        for (const rn of built.rules) link(rn, w, "fill", "fills", s.worklist.set_line);
        filled.set(s.worklist.name, w);
      } else {
        for (const sink of sinks) link(built.head, ports.get(sink.name), "write", "writes", s.set_line);
      }
    }
    // the worklist edges: from the stage that fills one to the pile that reads it
    for (const [pn, w] of wl) link(filled.get(w.name), pn, "read", "reads", w.set_line);
    // a gate between each pair of stages
    heads.forEach((h, i) => {
      const next = heads[i + 1];
      if (!next) return;
      const s = model.stages[i + 1];
      const g = add(`${model.stages[i]["@id"]}/gate`, "gate", `gate ${model.stages[i].no} to ${s.no}`, s.set_line);
      link(h.head, g, "gate", "", s.set_line);
      link(g, next.head, "gate", "", s.set_line);
    });
  } else {
    const members = model.rules;
    const built = stageGroup(model.piles ? model.piles["@id"] : `${model["@id"]}/rules`, "rules", model.piles ? model.piles.set_line : model.set_line, model.piles, members);
    heads.push(built);
    for (const sink of sinks) link(built.head, ports.get(sink.name), "write", "writes", model.set_line);
  }
  if (model.disabled?.length) {
    const g = group(`${model["@id"]}/disabled`, "disabled rules", model.disabled[0].set_line);
    for (const r of model.disabled) put(g, r["@id"], "rule-disabled", `${r.name}\n${r.check_class}`, r.set_line);
  }
  link(root, heads[0].head, "flow", "", model.set_line);

  const sc = model.schedule;
  if (sc) link(add(sc["@id"], "schedule", `schedule: every ${sc.every}${sc.at ? ` at ${sc.at}` : ""}`, sc.set_line), heads[0].head, "flow", "starts", sc.set_line);

  const rs = model.resilience;
  if (rs) {
    const lines = [`retry ${rs.retry.max}x, backoff ${rs.retry.backoff} s`, `stale after ${rs.stale.seconds} s`];
    if (rs.fuses.max_alerts) lines.push(`fuse: ${rs.fuses.max_alerts.count} alerts a rule`);
    if (rs.fuses.kill) lines.push(`fuse: kill row in ${rs.fuses.kill.table.toUpperCase()}`);
    lines.push(`dry run: ${rs.dry_run.value === "abap_true" ? "on" : "off"}`, `keep ${rs.keep.days} days`);
    link(root, add(rs["@id"], "resilience", `resilience\n${lines.join("\n")}`, rs.set_line), "config", "", rs.set_line);
  }

  const gv = model.governor;
  if (gv) {
    const n = add(gv["@id"], "governor", `governor\nglass ${gv.glass}, per pile ${gv.per_pile}\nwarn ${per(gv.warn)}, narrow at ${per(gv.narrow_at)}\nautoclose port ${gv.autoclose_port}`, gv.set_line);
    link(root, n, "config", "", gv.set_line);
    if (ports.has(gv.autoclose_port)) link(n, ports.get(gv.autoclose_port), "use", "autocloses via", gv.set_line);
  }

  const sm = model.simulate;
  if (sm) {
    const n = add(sm["@id"], "simulate", `simulate\nseed ${sm.seed.value}, scale ${Number(sm.scale.value) / 1e6}`, sm.set_line);
    link(root, n, "config", "", sm.set_line);
    const work = model.ports.find((p) => p.is_work);
    if (work) link(n, ports.get(work.name), "use", "work twin", sm.set_line);
  }

  const ck = model.cockpit;
  if (ck) link(root, add(ck["@id"], "cockpit", "cockpit", ck.set_line), "config", "", ck.set_line);

  return {set: model.set, source: model.source, nodes, edges, groups};
}

export function graphJson(graph) {
  return `${JSON.stringify(graph, null, 2)}\n`;
}

const NODE_SHAPE = {
  set: ["([", "])"], stage: ["[[", "]]"], gate: ["{{", "}}"], pile: ["[(", ")]"], worklist: ["[(", ")]"],
  "port-source": [">", "]"], "port-sink": [">", "]"], "port-autoclose": [">", "]"], "port-work": [">", "]"],
};
const ARROW = {flow: "-->", gate: "==>", read: "-.->", fill: "-.->", write: "-->", config: "-.->", use: "-.->"};
// A label is literal text: # & < > and " go out as Mermaid entities first (# first, it starts one),
// so the <br/> breaks added after are the only tags in it. Brackets are safe inside the quotes.
const ENTITY = {"#": "#35;", "&": "#amp;", "<": "#lt;", ">": "#gt;", '"': "#quot;"};
const text = (s) => s.replace(/[#&<>"]/g, (c) => ENTITY[c]).split("\n").join("<br/>");

// Node ids: the model's @id with everything outside letters and digits made
// _, in the order the nodes were made; a clash gets a counter.
function mermaidIds(nodes) {
  const ids = new Map();
  const taken = new Set();
  for (const n of nodes) {
    const base = `n_${n.id.replace(/[^A-Za-z0-9]/g, "_")}`;
    let id = base;
    for (let k = 2; taken.has(id); k++) id = `${base}_${k}`;
    taken.add(id);
    ids.set(n.id, id);
  }
  return ids;
}

export function graphMermaid(graph) {
  const ids = mermaidIds(graph.nodes);
  const out = ["flowchart LR"];
  const draw = (n, pad) => {
    const [a, b] = NODE_SHAPE[n.kind] ?? ["[", "]"];
    out.push(`${pad}${ids.get(n.id)}${a}"${text(n.label)}"${b}`);
  };
  const byId = new Map(graph.nodes.map((n) => [n.id, n]));
  for (const n of graph.nodes) if (!n.group) draw(n, "  ");
  for (const g of graph.groups) {
    out.push(`  subgraph ${ids.get(g.nodes[0]) ?? `g_${g.id.replace(/[^A-Za-z0-9]/g, "_")}`}_group["${text(g.label)}"]`);
    out.push("    direction TB");
    for (const id of g.nodes) draw(byId.get(id), "    ");
    out.push("  end");
  }
  for (const e of graph.edges) out.push(`  ${ids.get(e.from)} ${ARROW[e.kind]}${e.label ? `|"${text(e.label)}"|` : ""} ${ids.get(e.to)}`);
  return `${out.join("\n")}\n`;
}

// docs: the block of a document between the markers of one set
export function docBlock(set, mermaid) {
  return `${DOC_BEGIN(set)}\n\`\`\`mermaid\n${mermaid}\`\`\`\n${DOC_END(set)}`;
}

// What differs between a document's copy of the diagram and the command's output; "" when none.
export function docDrift(docFile, set, mermaid) {
  const doc = readFileSync(docFile, "utf8");
  const from = doc.indexOf(DOC_BEGIN(set));
  const to = doc.indexOf(DOC_END(set));
  if (from < 0 || to < from) return `${docFile}: no diagram block for set ${set} (${DOC_BEGIN(set)} ... ${DOC_END(set)})`;
  const copy = doc.slice(from, to + DOC_END(set).length);
  return copy === docBlock(set, mermaid) ? "" : `${docFile}: the diagram of ${set} differs from the command's output; regenerate it with: node tools/dsl-l3.mjs graph <set> --mermaid`;
}
