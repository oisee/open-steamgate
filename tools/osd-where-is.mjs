#!/usr/bin/env node
// Build the feature-to-file map from the repository's discoverable inventories.
import {existsSync, readFileSync, readdirSync, writeFileSync} from "node:fs";
import {dirname, join, relative} from "node:path";
import {fileURLToPath} from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(join(root, path), "utf8");
const files = (dir, suffix) => readdirSync(join(root, dir), {withFileTypes: true})
  .filter((entry) => entry.isFile() && entry.name.endsWith(suffix))
  .map((entry) => `${dir}/${entry.name}`).sort();
const dirs = (dir) => readdirSync(join(root, dir), {withFileTypes: true})
  .filter((entry) => entry.isDirectory()).map((entry) => `${dir}/${entry.name}`).sort();
const json = (path) => JSON.parse(read(path));
const assertPath = (path) => {
  if (!existsSync(join(root, path))) throw new Error(`missing path: ${path}`);
  return path;
};
const link = (path, label = path) => `[${label}](../${assertPath(path)})`;
const plain = (value) => value.replace(/[|\[\]]/g, " ").replace(/\s+/g, " ").trim();
const title = (path) => plain(read(path).match(/^#\s+(.+)$/m)?.[1] ?? path);
const header = (path) => plain(read(path).replace(/^#![^\n]*\n/, "").match(/^\/\/\s*(.+)$/m)?.[1] ?? "");

const packageScripts = json("package.json").scripts;
const scriptTargets = new Map();
for (const [name, command] of Object.entries(packageScripts)) {
  const targets = [...command.matchAll(/\b(?:node|bun|sh)\s+((?:tools|scripts|test)\/[^\s'";]+\.(?:mjs|sh))\b/g)]
    .map((match) => assertPath(match[1]));
  scriptTargets.set(name, targets);
}
const suites = json("test/suites.json");
const testPaths = [...new Set([...suites.files, ...Object.values(suites.groups ?? {}).flat(),
  ...[...scriptTargets.values()].flat().filter((path) => path.startsWith("test/"))])].map(assertPath);
const docs = files("docs", ".md");
const tools = files("tools", ".mjs");
const sources = dirs("src");
const goPackages = dirs("tools/gogen/go").filter((path) =>
  readdirSync(join(root, path)).some((file) => file.endsWith(".go")));
const packs = dirs("packs").map((path) => `${path}/osd-pack.json`).filter((path) => existsSync(join(root, path)));
const mainPaths = [...tools, ...sources, ...goPackages, ...packs];
const wildcard = (pattern) => new RegExp(`^${pattern.split("*").map((part) =>
  part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join(".*")}$`);
const select = (patterns, candidates, feature, kind) => patterns.flatMap((pattern) => {
  const matches = candidates.filter((candidate) => wildcard(pattern).test(candidate));
  if (!matches.length) throw new Error(`${feature}: ${kind} selector has no match: ${pattern}`);
  return matches;
}).filter((value, index, all) => all.indexOf(value) === index);

const rows = [
  "# Where is it?",
  "",
  "Generated by `npm run where` from `tools/where-is.features.json`, package scripts,",
  "`test/suites.json`, document titles, tool header comments, source folders, Go packages, and pack manifests.",
  "The feature list groups discovered paths; each linked path is checked when this page is built.",
  "",
];
for (const feature of json("tools/where-is.features.json")) {
  if (!feature.name || !Array.isArray(feature.main) || !Array.isArray(feature.tests) || !Array.isArray(feature.docs) || !Array.isArray(feature.commands)) {
    throw new Error("each feature needs name, commands, main, tests, and docs arrays");
  }
  const commands = select(feature.commands, Object.keys(packageScripts), feature.name, "command");
  const main = select(feature.main, mainPaths, feature.name, "main file");
  const tests = select(feature.tests, testPaths, feature.name, "test");
  const reading = select(feature.docs, docs, feature.name, "doc");
  rows.push(`## ${plain(feature.name)}`, "");
  if (commands.length) rows.push(`- Commands: ${commands.map((name) => {
    const targets = scriptTargets.get(name);
    return `\`npm run ${name}\` (${targets.length ? targets.map((path) => link(path)).join(", ") : link("package.json")})`;
  }).join("; ")}`);
  rows.push(`- Main files: ${main.map((path) => {
    const summary = path.startsWith("tools/") && path.endsWith(".mjs") ? header(path) : "";
    return `${link(path)}${summary ? ` — ${summary}` : ""}`;
  }).join("; ")}`);
  rows.push(`- Tests: ${tests.map((path) => link(path)).join("; ")}`);
  rows.push(`- Docs: ${reading.map((path) => link(path, title(path))).join("; ")}`, "");
}

const output = rows.join("\n");
const destination = "docs/where-is.md";
if (process.argv.includes("--check")) {
  if (!existsSync(join(root, destination)) || read(destination) !== output) {
    console.error(`${destination} is stale; run npm run where`);
    process.exitCode = 1;
  }
} else {
  writeFileSync(join(root, destination), output);
  console.log(`Wrote ${relative(process.cwd(), join(root, destination))}`);
}
